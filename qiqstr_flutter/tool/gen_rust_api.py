import glob
import os
import re
import subprocess
import sys

app = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
shared_api = os.path.join(app, "..", "qiqstr_rust", "src", "api")
out_dir = os.path.join(app, "rust", "src", "api")

skip_modules = {"mod", "marmot", "nip44"}
dart_async = {
    "set_active_mute_list",
    "extract_pubkeys_from_events",
    "filter_reply_event_ids",
    "extract_repost_original_ids",
}

pattern = re.compile(r"\n((?:///[^\n]*\n)*)pub (async )?fn (\w+)\s*\((.*?)\)\s*(?:->\s*([^{]+?))?\s*\{", re.S)


def split_params(args):
    params, depth, current = [], 0, ""
    for ch in args:
        if ch in "<(":
            depth += 1
        elif ch in ">)":
            depth -= 1
        if ch == "," and depth == 0:
            params.append(current)
            current = ""
        else:
            current += ch
    params.append(current)
    return [" ".join(p.split()) for p in params if p.strip()]


modules = []
for path in sorted(glob.glob(os.path.join(shared_api, "*.rs"))):
    module = os.path.basename(path)[:-3]
    if module in skip_modules:
        continue
    modules.append(module)
    source = open(path).read()
    lines = [
        "// Generated by tool/gen_rust_api.py from qiqstr_rust/src/api. Do not edit.",
        "#![allow(clippy::too_many_arguments)]",
        "",
        "use anyhow::Result;",
        "use flutter_rust_bridge::frb;",
        "",
        "use crate::frb_generated::StreamSink;",
        "use crate::sink::dart_sink;",
        "",
    ]
    uses_sink = False
    uses_frb = False
    uses_result = False
    for match in pattern.finditer(source):
        docs, is_async, name, args = match.group(1), bool(match.group(2)), match.group(3), match.group(4)
        ret = (match.group(5) or "").strip()
        signature, call = [], []
        for param in split_params(args):
            pname, ptype = [x.strip() for x in param.split(":", 1)]
            signature.append(f"{pname}: {ptype}")
            if ptype.startswith("StreamSink"):
                uses_sink = True
                call.append(f"dart_sink({pname})")
            else:
                call.append(pname)
        if ret.startswith("Result"):
            uses_result = True
        target = f"qiqstr::api::{module}::{name}({', '.join(call)})"
        returns = f" -> {ret}" if ret else ""
        lines += docs.splitlines()
        if is_async:
            lines += [f"pub async fn {name}({', '.join(signature)}){returns} {{", f"    {target}.await", "}", ""]
        else:
            if name not in dart_async:
                uses_frb = True
                lines.append("#[frb(sync)]")
            lines += [f"pub fn {name}({', '.join(signature)}){returns} {{", f"    {target}", "}", ""]
    if not uses_result:
        lines.remove("use anyhow::Result;")
    if not uses_frb:
        lines.remove("use flutter_rust_bridge::frb;")
    if not uses_sink:
        lines.remove("use crate::frb_generated::StreamSink;")
        lines.remove("use crate::sink::dart_sink;")
    while lines[-1] == "":
        lines.pop()
    open(os.path.join(out_dir, f"{module}.rs"), "w").write("\n".join(lines) + "\n")

open(os.path.join(out_dir, "mod.rs"), "w").write("".join(f"pub mod {m};\n" for m in modules))

for stale in glob.glob(os.path.join(out_dir, "*.rs")):
    name = os.path.basename(stale)[:-3]
    if name != "mod" and name not in modules:
        os.remove(stale)

subprocess.run(["cargo", "fmt", "--manifest-path", os.path.join(app, "rust", "Cargo.toml")], check=True)
print(f"Wrote {len(modules)} modules to rust/src/api", file=sys.stderr)
